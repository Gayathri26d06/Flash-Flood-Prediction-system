import { useEffect, useMemo, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { BellOff, ShieldAlert } from 'lucide-react'
import AlertCard from '../components/AlertCard'
import Loading from '../components/Loading'
import ErrorMessage from '../components/ErrorMessage'
import ActiveLocationPanel from '../components/ActiveLocationPanel'
import ActiveScenarioCard from '../components/ActiveScenarioCard'
import RiskBadge from '../components/RiskBadge'
import useRealtimeData from '../hooks/useRealtimeData'
import { getAlerts, updateAlertStatus, getScenarioAlerts } from '../services/api'
import { useActiveLocation } from '../context/LocationContext'
import { useActiveScenario } from '../context/ScenarioContext'
import { getRiskMeta, riskRank } from '../utils/riskUtils'

const STATUS_FILTERS = ['ALL', 'ACTIVE', 'ACKNOWLEDGED', 'RESOLVED']

export default function Alerts() {
  const { selectedLocation, alerts: activeLocationAlerts, loading: activeLoading } = useActiveLocation()
  const { scenario, scenarioAlert } = useActiveScenario()
  const [alerts, setAlerts] = useState([])
  const [scenarioAlerts, setScenarioAlerts] = useState([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState(null)
  const [statusFilter, setStatusFilter] = useState('ALL')
  const navigate = useNavigate()

  const load = async () => {
    setLoading(true)
    setError(null)
    const res = await getAlerts()
    if (res.success) setAlerts(Array.isArray(res.data) ? res.data : [])
    else setError(res.error)
    setLoading(false)
  }

  // Alerts generated by previous manual scenarios. Each scenario has at
  // most one alert (UNIQUE key on scenario_id in MySQL), so re-loading
  // this page can never create or show duplicates.
  const loadScenarioAlerts = async () => {
    const res = await getScenarioAlerts()
    if (res.success) setScenarioAlerts(Array.isArray(res.data) ? res.data : [])
  }

  useEffect(() => {
    load()
    loadScenarioAlerts()
  }, [])

  // Re-read scenario alerts whenever a new scenario becomes active.
  useEffect(() => {
    if (scenario?.scenario_id) loadScenarioAlerts()
  }, [scenario?.scenario_id])

  useRealtimeData({
    new_alert: (payload) => {
      // Scenario alerts are broadcast on the same channel but are already
      // rendered by ScenarioAlertPanel / Previous Scenario Alerts above —
      // routing them here too would show the same alert twice.
      if (payload?.source === 'MANUAL_SCENARIO') {
        setScenarioAlerts((prev) =>
          prev.some((a) => a.id === payload.id) ? prev : [payload, ...prev]
        )
        return
      }
      setAlerts((prev) => [{ status: 'ACTIVE', created_at: new Date().toISOString(), ...payload }, ...prev])
    },
  })

  const filtered = useMemo(() => {
    const base = statusFilter === 'ALL' ? alerts : alerts.filter((a) => a.status === statusFilter)
    return [...base].sort((a, b) => {
      if (a.status !== b.status) {
        if (a.status === 'ACTIVE') return -1
        if (b.status === 'ACTIVE') return 1
      }
      return riskRank(b.severity || b.risk_level) - riskRank(a.severity || a.risk_level)
    })
  }, [alerts, statusFilter])

  const counts = useMemo(
    () => ({
      ALL: alerts.length,
      ACTIVE: alerts.filter((a) => a.status === 'ACTIVE').length,
      ACKNOWLEDGED: alerts.filter((a) => a.status === 'ACKNOWLEDGED').length,
      RESOLVED: alerts.filter((a) => a.status === 'RESOLVED').length,
    }),
    [alerts]
  )

  const mutateStatus = async (alert, status) => {
    setAlerts((prev) => prev.map((a) => (a.id === alert.id ? { ...a, status } : a)))
    await updateAlertStatus(alert.id, { status })
  }

  return (
    <div className="space-y-4">
      <ActiveScenarioCard title="ALERTS — ACTIVE DISASTER SCENARIO" compact />

      {/* The alert auto-generated from the active scenario. LOW-risk
          scenarios intentionally produce no emergency alert. */}
      {scenario && <ScenarioAlertPanel scenario={scenario} alert={scenarioAlert} />}

      <ActiveLocationPanel title="ALERTS — ACTIVE LOCATION" />

      {selectedLocation && (
        <div className="panel p-4">
          <h2 className="text-sm font-semibold text-ink mb-2.5">
            Alerts for {selectedLocation.name}
          </h2>
          {activeLoading ? (
            <Loading variant="inline" label="Checking active-location alerts…" />
          ) : activeLocationAlerts.length === 0 ? (
            <p className="text-sm text-ink-faint">No active alerts for {selectedLocation.name} right now.</p>
          ) : (
            <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
              {activeLocationAlerts.map((alert) => (
                <AlertCard key={alert.id} alert={alert} />
              ))}
            </div>
          )}
        </div>
      )}

      {scenarioAlerts.length > 1 && (
        <div className="panel p-4">
          <h2 className="text-sm font-semibold text-ink mb-2.5">Previous Scenario Alerts</h2>
          <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
            {scenarioAlerts
              .filter((a) => a.scenario_id !== scenario?.scenario_id)
              .map((a) => (
                <AlertCard key={`scenario-${a.id}`} alert={a} compact />
              ))}
          </div>
        </div>
      )}

      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h1 className="text-lg font-semibold text-ink">Alerts</h1>
          <p className="text-sm text-ink-muted">
            Emergency notifications generated by the risk engine (network-wide, seeded demo locations).
          </p>
        </div>
        <div className="flex gap-1.5 flex-wrap">
          {STATUS_FILTERS.map((s) => (
            <button
              key={s}
              onClick={() => setStatusFilter(s)}
              className={`text-xs font-mono px-3 py-1.5 rounded-full border transition-colors ${
                statusFilter === s
                  ? 'bg-signal/15 text-signal border-signal/40'
                  : 'bg-panel-raised text-ink-muted border-panel-border hover:text-ink'
              }`}
            >
              {s} <span className="text-ink-faint ml-1">{counts[s]}</span>
            </button>
          ))}
        </div>
      </div>

      {loading ? (
        <Loading label="Loading alert feed…" />
      ) : error ? (
        <ErrorMessage variant="offline" message={error} onRetry={load} />
      ) : filtered.length === 0 ? (
        <div className="panel py-16 text-center text-ink-faint text-sm">No alerts match this filter.</div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
          {filtered.map((alert) => (
            <AlertCard
              key={alert.id ?? alert.alert_id}
              alert={alert}
              onAcknowledge={(a) => mutateStatus(a, 'ACKNOWLEDGED')}
              onResolve={(a) => mutateStatus(a, 'RESOLVED')}
              onViewLocation={(a) => navigate(`/risk-map?location=${a.location_id}`)}
            />
          ))}
        </div>
      )}
    </div>
  )
}

/**
 * Renders the alert derived from the ACTIVE DISASTER SCENARIO.
 *
 * Severity mapping (see backend/services/scenarioService.js):
 *   LOW      -> informational advisory, no emergency alert
 *   MODERATE -> FLOOD WARNING
 *   HIGH     -> HIGH RISK FLOOD ALERT
 *   CRITICAL -> CRITICAL FLOOD ALERT
 */
function ScenarioAlertPanel({ scenario, alert }) {
  const { location, environment, prediction } = scenario
  const meta = getRiskMeta(prediction.risk_level)

  if (!alert) {
    return (
      <div className="panel p-4 flex items-start gap-3">
        <BellOff className="w-4 h-4 text-risk-low shrink-0 mt-0.5" />
        <div>
          <p className="text-sm font-medium text-ink">
            No emergency alert for {location.name}
          </p>
          <p className="text-xs text-ink-muted mt-1">
            The active scenario is {prediction.risk_level} risk
            ({Number(prediction.probability).toFixed(1)}% model probability), which does not warrant an
            emergency alert. {scenario.recommended_action}
          </p>
        </div>
      </div>
    )
  }

  const rows = [
    ['Location', [location.name, location.state].filter(Boolean).join(', ')],
    ['Risk Level', alert.severity],
    ['Disaster Probability', `${Number(alert.probability).toFixed(1)}%`],
    ['Rainfall', `${environment.rainfall} mm`],
    ['Humidity', `${environment.humidity} %`],
    ['Soil Moisture', `${environment.soil_moisture} %`],
    ['Timestamp', alert.created_at ? new Date(alert.created_at).toLocaleString() : '—'],
  ]

  return (
    <div className="panel p-4 border-l-[3px]" style={{ borderLeftColor: meta.hex }}>
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div className="flex items-center gap-2">
          <ShieldAlert
            className={`w-5 h-5 ${alert.severity === 'CRITICAL' ? 'text-risk-critical animate-blink' : ''}`}
            style={alert.severity !== 'CRITICAL' ? { color: meta.hex } : undefined}
            strokeWidth={1.75}
          />
          <div>
            <h2 className="text-base font-semibold" style={{ color: meta.hex }}>
              {alert.title}
            </h2>
            <p className="text-[10px] font-mono uppercase tracking-wide text-ink-faint mt-0.5">
              Auto-generated from the active disaster scenario · Alert #{alert.id}
            </p>
          </div>
        </div>
        <RiskBadge level={alert.severity} size="lg" pulse={alert.severity === 'CRITICAL'} />
      </div>

      <div className="mt-3 divide-y divide-panel-border border-t border-b border-panel-border">
        {rows.map(([label, value]) => (
          <div key={label} className="flex items-center justify-between py-2 text-sm">
            <span className="text-ink-muted">{label}</span>
            <span className="font-mono text-ink text-right">{value}</span>
          </div>
        ))}
      </div>

      <div
        className="mt-3 rounded-md px-3 py-2.5 text-xs leading-relaxed"
        style={{ background: `${meta.hex}0d`, border: `1px solid ${meta.hex}4d`, color: meta.hex }}
      >
        <span className="font-semibold">Recommended Action: </span>
        {alert.recommended_action}
      </div>
    </div>
  )
}
